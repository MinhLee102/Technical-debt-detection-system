select PROJECT_ID, CREATION_DATE, CLOSE_DATE, createCommitHash as creationCommitHash, closeCommitHash, TYPE, RULE, COMPONENT, SEVERITY, START_LINE, END_LINE, RESOLUTION, STATUS, MESSAGE, EFFORT, DEBT
from 
(select SONAR_ANALYSIS.REVISION as closeCommitHash, * from
(select SONAR_ISSUES.*, SONAR_ANALYSIS.REVISION as createCommitHash
FROM SONAR_ISSUES, SONAR_ANALYSIS
where SONAR_ANALYSIS.ANALYSIS_KEY=SONAR_ISSUES.CREATION_ANALYSIS_KEY) as A

left join SONAR_ANALYSIS
on
A.CLOSE_ANALYSIS_KEY=SONAR_ANALYSIS.ANALYSIS_KEY)